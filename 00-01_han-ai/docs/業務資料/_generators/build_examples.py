HEAD_FILL = PatternFill("solid", start_color="E4EFEA")
HEAD_FONT = Font(bold=True, color="1A2233")
NOTE_FONT = Font(color="5B6472")
TITLE_FONT = Font(bold=True, size=13, color="1A2233")
THIN = Side(style="thin", color="C9D2CE")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WRAP = Alignment(wrap_text=True, vertical="top")
WRAP_MID = Alignment(wrap_text=True, vertical="center")


def style_header(ws, ncols, row=1):
    for c in range(1, ncols + 1):
        cc = ws.cell(row=row, column=c)
        cc.fill = HEAD_FILL; cc.font = HEAD_FONT; cc.border = BORDER; cc.alignment = WRAP_MID
    ws.freeze_panes = ws.cell(row=row + 1, column=1)


def put(ws, headers, rows, widths=None, start_row=1):
    for j, h in enumerate(headers, 1):
        ws.cell(row=start_row, column=j, value=h)
    style_header(ws, len(headers), row=start_row)
    for i, r in enumerate(rows, start_row + 1):
        for j, v in enumerate(r, 1):
            cc = ws.cell(row=i, column=j, value=v); cc.border = BORDER; cc.alignment = WRAP
    if widths:
        for j, w in enumerate(widths, 1):
            ws.column_dimensions[ws.cell(row=1, column=j).column_letter].width = w


def howto(wb, lines):
    ws = wb.create_sheet("この記入例について", 0)
    ws.column_dimensions["A"].width = 110
    ws["A1"] = lines[0]; ws["A1"].font = TITLE_FONT
    r = 3
    for ln in lines[1:]:
        c = ws.cell(row=r, column=1, value=ln); c.alignment = WRAP
        c.font = NOTE_FONT if ln.startswith(("　", "・")) else Font(color="1A2233")
        r += 1


def save(wb, layer, name):
    p = os.path.join(EX, layer, name)
    wb.save(p); print("  ", os.path.relpath(p, ROOT).replace(os.sep, "/"))


